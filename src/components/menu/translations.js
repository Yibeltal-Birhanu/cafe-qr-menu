export function t(key, lang = 'en') {
  const dict = translations[lang] || translations.en;
  return dict[key] || translations.en[key] || key;
}

export function getLocalizedItem(item, lang = 'en') {
  if (!item) return { name: '', description: '' };
  if (lang === 'am' && itemTranslations[item.id]) {
    return {
      name: itemTranslations[item.id].name,
      description: itemTranslations[item.id].desc,
    };
  }
  return {
    name: item.name,
    description: item.description,
  };
}

export function getLocalizedCategory(category, lang = 'en') {
  if (!category) return { name: '' };
  if (lang === 'am' && categoryTranslations[category.id]) {
    return {
      ...category,
      name: categoryTranslations[category.id],
    };
  }
  return category;
}
